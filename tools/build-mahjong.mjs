import { build } from "esbuild";
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
await mkdir(new URL("public/vendor/", root), { recursive: true });
const result = await build({
  stdin: {
    contents: `export { default as Shoupai } from './node_modules/@kobalab/majiang-core/lib/shoupai.js';
export { hule } from './node_modules/@kobalab/majiang-core/lib/hule.js';
export { default as rule } from './node_modules/@kobalab/majiang-core/lib/rule.js';`,
    resolveDir: fileURLToPath(root),
  },
  bundle: true,
  format: "esm",
  platform: "browser",
  minify: true,
  write: false,
  banner: {
    js: "// @kobalab/majiang-core 1.4.1 · MIT · Satoshi Kobayashi. See mahjong-LICENSE.txt.\n// Generated by tools/build-mahjong.mjs; do not edit.",
  },
});
await writeFile(
  new URL("public/vendor/mahjong-scoring.js", root),
  result.outputFiles[0].contents,
);
await writeFile(
  new URL("public/vendor/mahjong-LICENSE.txt", root),
  await readFile(new URL("node_modules/@kobalab/majiang-core/LICENSE", root)),
);
